#!/usr/bin/env python3
"""Build the WinDevKit bindings pack: BridgeKit-generated C# and
Rust bindings for every kit header, as one zip + SHA256SUMS.txt.

Why this exists: BridgeKit generates bindings from a header on
demand, but a consumer landing on the Releases page should be
able to download every kit's bindings in one file, generated
from the headers exactly as they stand in this tree — no local
BridgeKit build required. Regenerate and re-release the pack
whenever a header changes; the version in the pack README is
the pack version, and each bindings file names its kit version.

Usage:
    python3 tools/bindings-pack.py [--version 1.0.0] [--out DIR]

Requires a built BridgeKit binary: kits/BridgeKit/target/release/
bridgekit (cargo build --release in kits/BridgeKit), or set
BRIDGEKIT=/path/to/bridgekit.
"""

import argparse
import hashlib
import os
import re
import subprocess
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def kit_facts():
    """(kit, header path, dll file name, kit version) per DLL kit."""
    facts = []
    kits_dir = os.path.join(ROOT, "kits")
    for kit in sorted(os.listdir(kits_dir)):
        kdir = os.path.join(kits_dir, kit)
        include = os.path.join(kdir, "include")
        if not os.path.isdir(include):
            continue  # BridgeKit itself: a CLI tool, no header/DLL.
        headers = [f for f in os.listdir(include) if f.endswith(".h")]
        if len(headers) != 1:
            sys.exit(f"{kit}: expected exactly one header, found {headers}")
        toml = open(os.path.join(kdir, "Cargo.toml")).read()
        lib = re.search(r'\[lib\]\s*\nname\s*=\s*"([^"]+)"', toml).group(1)
        version = re.search(r'^version\s*=\s*"([^"]+)"', toml, re.M).group(1)
        facts.append((kit, os.path.join(include, headers[0]), f"{lib}.dll", version))
    return facts


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", default="1.0.0", help="pack version (default 1.0.0)")
    ap.add_argument("--out", default=os.path.join(ROOT, "dist", "bindings"),
                    help="output directory (default dist/bindings)")
    args = ap.parse_args()

    bridgekit = os.environ.get(
        "BRIDGEKIT",
        os.path.join(ROOT, "kits", "BridgeKit", "target", "release", "bridgekit"))
    if not os.path.exists(bridgekit):
        sys.exit(f"bridgekit binary not found at {bridgekit}\n"
                 "build it: cargo build --release (in kits/BridgeKit), or set BRIDGEKIT=")

    facts = kit_facts()
    stage = os.path.join(args.out, "stage", f"WinDevKit-Bindings-{args.version}")
    cs_dir = os.path.join(stage, "csharp")
    rs_dir = os.path.join(stage, "rust")
    os.makedirs(cs_dir, exist_ok=True)
    os.makedirs(rs_dir, exist_ok=True)

    index = []
    for kit, header, dll, version in facts:
        subprocess.run([bridgekit, "gen-cs", "--header", header,
                        "--dll-name", dll, "--out", os.path.join(cs_dir, f"{kit}.cs")],
                       check=True, capture_output=True)
        subprocess.run([bridgekit, "gen-rs", "--header", header,
                        "--out", os.path.join(rs_dir, f"{kit}.rs")],
                       check=True, capture_output=True)
        index.append((kit, version, dll))
        print(f"{kit}: bindings generated (kit v{version})")

    with open(os.path.join(stage, "README.md"), "w") as f:
        f.write(f"""# WinDevKit Bindings Pack v{args.version}

C# and Rust bindings for every WinDevKit kit, generated by
[BridgeKit](https://github.com/SeanShaffer88/WinDevKit) from each
kit's own shipped C header — never retyped by hand, so a binding
can never quietly drift from the DLL it calls into.

- `csharp/<Kit>.cs` — `[DllImport]` declarations, one file per kit.
- `rust/<Kit>.rs` — `extern "C"` blocks, one file per kit.

Each file is standalone: drop the ones you need into your project.
The DLLs themselves are in this repository's Releases, one zip
per kit (e.g. `MediaKit-0.1.0-x64.zip`).

| Kit | Kit version | DLL |
|---|---|---|
""")
        for kit, version, dll in index:
            f.write(f"| {kit} | {version} | `{dll}` |\n")
        f.write("""
Regenerate or verify any single kit at any time with BridgeKit
itself (also in this repository):

    bridgekit gen-cs --header <kit.h> --dll-name <kit.dll> --out <Kit>.cs
    bridgekit gen-rs --header <kit.h> --out <Kit>.rs
    bridgekit verify --header <kit.h> --dll <kit.dll>
""")

    zip_name = f"WinDevKit-Bindings-{args.version}.zip"
    zip_path = os.path.join(args.out, zip_name)
    os.makedirs(args.out, exist_ok=True)
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
        for base, _dirs, files in os.walk(stage):
            for name in sorted(files):
                full = os.path.join(base, name)
                arc = os.path.relpath(full, os.path.join(stage, ".."))
                zi = zipfile.ZipInfo(arc, date_time=(1980, 1, 1, 0, 0, 0))
                zi.compress_type = zipfile.ZIP_DEFLATED
                z.writestr(zi, open(full, "rb").read())
    digest = hashlib.sha256(open(zip_path, "rb").read()).hexdigest()
    with open(os.path.join(args.out, "SHA256SUMS.txt"), "w") as f:
        f.write(f"{digest}  {zip_name}\n")
    print(f"\nwrote {zip_path}\n      {digest}  {zip_name}")


if __name__ == "__main__":
    main()
